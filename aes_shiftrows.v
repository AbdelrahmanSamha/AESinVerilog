module aes_shiftrows (
    input  wire [127:0] in,
    output wire [127:0] out
);








/*
		original state : 
		------------------------------------------------------
		|		b0		|		b4			|		b8		|		b12	  |
		|	 [7:0] 	|	 [39:32]	   |	[71:64]	|	[103:96]	  |
		|				|					|				|				  |
		|-----------|--------------|-----------|-------------|
		|		b1		|		b5			|		b9		|		b13	  |
		|	 [15:8] 	|	 [47:40]	   |	[79:72]	|	[111:104]  |
		|				|					|				|				  |
		|-----------|--------------|-----------|-------------|
		|		b2		|		b6			|		b10	|		b14	  |
		|	 [23:16]	|	 [55:48]	   |	[87:80]	|	[119:112]  |
		|				|					|				|				  |
		|-----------|--------------|-----------|-------------|
		|		b3		|		b7			|		b11	|		b15	  |
		|	 [31:24]	|	 [63:56]	   |	[95:88]	|	[127:120]  |
		|				|					|				|				  |
		------------------------------------------------------

		shifted  state : 
		------------------------------------------------------
		|		b0		|		b4			|		b8		|		b12	  |
		|	 [7:0] 	|	 [39:32]	   |	[71:64]  |	[103:96]   |
		|				|					|				|				  |
		|-----------|--------------|-----------|-------------|
		|		b5		|		b9			|		b13	|		b1 	  |
		|	 [47:40]	|	 [79:72]	   | [111:104] |	[15:8]	  |
		|				|					|				|				  |
		|-----------|--------------|-----------|-------------|
		|		b10	|		b14		|		b2 	|		b6 	  |
		|	 [87:80]	|	 [119:112]	|	[23:16]	|	[55:48]	  |
		|				|					|				|				  |
		|-----------|--------------|-----------|-------------|
		|		b15	|		b3			|		b7	   |		b11	  |
		| [127:120]	|	 [31:24] 	|	[63:56]	|	[95:88] 	  |
		|				|					|				|				  |
		------------------------------------------------------



*/


	//first row stays the same
	assign out[7:0] = in[7:0];
	assign out[39:32] = in[39:32];
	assign out[71:64] = in[71:64];
	assign out[103:96] = in[103:96];
	
	//2nd row is shifted to the left by one. 
	
	assign out [15:8] = in [47:40];
	assign out [47:40] = in [79:72];
	assign out [79:72] = in [111:104];
	assign out [111:104] = in [15:8];
	
	//3rd row is shifted to the left by two.
	assign out [23:16] = in [87:80];
	assign out [55:48] = in [119:112];
	assign out [87:80] = in [23:16];
	assign out [119:112] = in [55:48];
	
	//4th row is shifted to the left by three.
	assign out [31:24] = in [127:120];
	assign out [63:56] = in [31:24];
	assign out [95:88] = in [63:56];
	assign out [127:120] = in [95:88];
	


endmodule
