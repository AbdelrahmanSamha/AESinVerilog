module aes_shiftrows (
    input  wire [127:0] in,
    output wire [127:0] out
);








/*
		original state : 
		------------------------------------------------------
		|		b0		|		b4			|		b8		|		b12	  |
		| [127:120]	|	 [95:88]	   |	[63:56]	|	[31:24]	  |
		|				|					|				|				  |
		|-----------|--------------|-----------|-------------|
		|		b1		|		b5			|		b9		|		b13	  |
		| [119:112] |	 [87:80]	   |	[55:48]	|	 [23:16]   |
		|				|					|				|				  |
		|-----------|--------------|-----------|-------------|
		|		b2		|		b6			|		b10	|		b14	  |
		| [111:104] |	 [79:72]	   |	[47:40]	|	 [15:8]    |
		|				|					|				|				  |
		|-----------|--------------|-----------|-------------|
		|		b3		|		b7			|		b11	|		b15	  |
		|	[103:96] |	 [71:64]	   |	[39:32]	|	  [7:0]    |
		|				|					|				|				  |
		------------------------------------------------------

		shifted  state : 
		------------------------------------------------------
		|		b0		|		b4			|		b8		|		b12	  |
		| [127:120]	|	 [95:88]	   |	[63:56]  |	 [31:24]   |
		|				|					|				|				  |
		|-----------|--------------|-----------|-------------|
		|		b5		|		b9			|		b13	|		b1 	  |
		|	 [87:80]	|	 [55:48]	   |   [23:16]	|	[119:112]  |
		|				|					|				|				  |
		|-----------|--------------|-----------|-------------|
		|		b10	|		b14		|		b2 	|		b6 	  |
		|	 [47:40]	|	  [15:8]   	|	[111:104]|	[79:72]	  |
		|				|					|				|				  |
		|-----------|--------------|-----------|-------------|
		|		b15	|		b3			|		b7	   |		b11	  |
		|    [7:0] 	|	 [103:96] 	|	[71:64]	|	[39:32] 	  |
		|				|					|				|				  |
		------------------------------------------------------


		
	

*/


 // Row 0 (no shift)
   assign out[127:120] = in[127:120]; // b0
   assign out[95:88]   = in[95:88];   // b4
   assign out[63:56]   = in[63:56];   // b8
   assign out[31:24]   = in[31:24];   // b12

   // Row 1 (left shift by 1)
   assign out[119:112] = in[87:80];    // b1 <- b5
   assign out[87:80]   = in[55:48];    // b5 <- b9
   assign out[55:48]   = in[23:16];    // b9 <- b13
   assign out[23:16]   = in[119:112];  // b13 <- b1

   // Row 2 (left shift by 2)
   assign out[111:104] = in[47:40];     // b2 <- b10
   assign out[79:72]   = in[15:8];      // b6 <- b14
   assign out[47:40]   = in[111:104];   // b10 <- b2
   assign out[15:8]    = in[79:72];     // b14 <- b6

   // Row 3 (left shift by 3)
   assign out[103:96]  = in[7:0];       // b3 <- b15
   assign out[71:64]   = in[103:96];    // b7 <- b3
   assign out[39:32]   = in[71:64];     // b11 <- b7
   assign out[7:0]     = in[39:32];     // b15 <- b11



endmodule
